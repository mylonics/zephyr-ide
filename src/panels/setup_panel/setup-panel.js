function updateHostToolsStatus(data, error) {
    const managerStatus = document.getElementById('manager-status');
    const packagesStatus = document.getElementById('packages-status');
    const installAllBtn = document.getElementById('install-all-btn');

    if (!managerStatus || !packagesStatus) {
        return;
    }

    if (error) {
        managerStatus.innerHTML = `<div class="error">Error: ${escapeHtml(error)}</div>`;
        packagesStatus.innerHTML = `<div class="error">Unable to check package status</div>`;
        return;
    }

    // Update package manager status
    if (!data.managerAvailable) {
        managerStatus.innerHTML = `
            <div class="warning">
                <strong>${escapeHtml(data.managerName)}</strong> is not installed or not in PATH.
                <div style="margin-top: 10px;">
                    <button class="button button-secondary" onclick="installPackageManagerTool()">
                        Install ${escapeHtml(data.managerName)}
                    </button>
                </div>
            </div>
        `;
    } else {
        managerStatus.innerHTML = `
            <div class="success">
                ✓ <strong>${escapeHtml(data.managerName)}</strong> is available
            </div>
        `;
    }

    // Update packages status
    if (!data.packages || data.packages.length === 0) {
        packagesStatus.innerHTML = '<div class="info">No packages to check</div>';
        return;
    }

    let html = '<table class="packages-table">';
    html += '<thead><tr><th>Package</th><th>Status</th><th>Action</th></tr></thead><tbody>';

    let actuallyMissing = false;
    for (const pkg of data.packages) {
        // Check if this package has a saved pending-restart state
        const savedState = hostToolsInstallationState.packageStates[pkg.name];
        const isPendingRestart = savedState === 'pending-restart';
        const isInstalling = savedState === 'installing';

        // Determine the actual state to display
        let statusClass, statusText, showInstallButton;

        if (isInstalling) {
            statusClass = 'info';
            statusText = '<span class="codicon codicon-sync codicon-modifier-spin"></span> Installing';
            showInstallButton = false;
        } else if (isPendingRestart) {
            statusClass = 'warning';
            statusText = '<span class="codicon codicon-warning"></span> Not Available Pending Restart';
            showInstallButton = false;
        } else if (pkg.available) {
            statusClass = 'success';
            statusText = '✓ Installed';
            showInstallButton = false;
        } else {
            statusClass = 'error';
            statusText = '✗ Not Available';
            showInstallButton = true;
            actuallyMissing = true;
        }

        html += `<tr>
            <td><strong>${escapeHtml(pkg.name)}</strong></td>
            <td><span class="${statusClass}">${statusText}</span></td>
            <td>`;

        if (showInstallButton) {
            html += `<button class="button button-small" onclick="installSinglePackage('${escapeHtml(pkg.name)}')">Install</button>`;
        }

        html += `</td></tr>`;
    }

    html += '</tbody></table>';
    packagesStatus.innerHTML = html;

    // Enable/disable install all button - disable if installation in progress or no packages to install
    if (installAllBtn) {
        installAllBtn.disabled = !actuallyMissing || !data.managerAvailable || hostToolsInstallationState.inProgress;
    }
}

function handleHostToolsStartInstallAll() {
    // Get current status and filter packages
    const packagesStatus = document.getElementById('packages-status');
    if (!packagesStatus) {
        return;
    }

    const table = packagesStatus.querySelector('.packages-table');
    if (!table) {
        return;
    }

    const packagesToInstall = [];
    const rows = table.querySelectorAll('tbody tr');

    for (const row of rows) {
        const nameCell = row.querySelector('td:first-child strong');
        if (!nameCell) {
            continue;
        }

        const packageName = nameCell.textContent.trim();
        const savedState = hostToolsInstallationState.packageStates[packageName];
        const isPendingRestart = savedState === 'pending-restart';
        const isInstalling = savedState === 'installing';

        // Only install if there's an install button (meaning not available and not pending restart)
        const installButton = row.querySelector('.button');
        if (installButton && !isPendingRestart && !isInstalling) {
            packagesToInstall.push(packageName);
        }
    }

    // Send the filtered list back to the extension
    vscode.postMessage({
        command: 'installAllMissingToolsPackages',
        packageNames: packagesToInstall
    });
}

function handleHostToolsInstallAllStarted(total) {
    hostToolsInstallationState.inProgress = true;
    const installAllBtn = document.getElementById('install-all-btn');
    if (installAllBtn) {
        installAllBtn.disabled = true;
        installAllBtn.innerHTML = `
            <span class="codicon codicon-sync codicon-modifier-spin"></span>
            Installing Packages (0/${total})
        `;
    }
}

function handleHostToolsPackageInstalling(packageName, current, total) {
    // Update the button text only if installing multiple packages
    if (total > 1) {
        const installAllBtn = document.getElementById('install-all-btn');
        if (installAllBtn) {
            // Ensure values are numbers to prevent XSS
            const currentNum = Number(current);
            const totalNum = Number(total);
            installAllBtn.innerHTML = `
                <span class="codicon codicon-sync codicon-modifier-spin"></span>
                Installing Packages (${currentNum}/${totalNum})
            `;
        }
    }

    // Save the state and update the specific package row in the table
    hostToolsInstallationState.packageStates[packageName] = 'installing';
    updateHostToolsPackageStatus(packageName, 'installing');
}

function handleHostToolsPackageInstalled(packageName, success, pendingRestart, current, total) {
    // Update and save package state
    let state = 'error';
    if (success && !pendingRestart) {
        state = 'installed';
    } else if (success && pendingRestart) {
        state = 'pending-restart';
    }

    hostToolsInstallationState.packageStates[packageName] = state;
    updateHostToolsPackageStatus(packageName, state);
}

function handleHostToolsInstallAllComplete(needsRestart, hasErrors) {
    hostToolsInstallationState.inProgress = false;
    const installAllBtn = document.getElementById('install-all-btn');
    if (installAllBtn) {
        if (needsRestart) {
            installAllBtn.innerHTML = `
                <span class="codicon codicon-warning"></span>
                Pending Restart
            `;
        } else if (hasErrors) {
            installAllBtn.innerHTML = `
                <span class="codicon codicon-error"></span>
                Installation Failed
            `;
        } else {
            installAllBtn.innerHTML = `
                <span class="codicon codicon-check"></span>
                All Packages Installed
            `;
        }

        // Re-enable button after a delay
        setTimeout(() => {
            installAllBtn.disabled = false;
            refreshHostToolsStatus();
        }, 2000);
    }
}

function updateHostToolsPackageStatus(packageName, state) {
    const packagesTable = document.querySelector('.packages-table');
    if (!packagesTable) {
        return;
    }

    const rows = packagesTable.querySelectorAll('tbody tr');
    for (const row of rows) {
        const nameCell = row.querySelector('td:first-child strong');
        if (nameCell && nameCell.textContent.trim() === packageName) {
            const statusCell = row.querySelector('td:nth-child(2)');
            const actionCell = row.querySelector('td:nth-child(3)');

            if (!statusCell) {
                continue;
            }

            // Update status text and style
            switch (state) {
                case 'installing':
                    statusCell.innerHTML = '<span class="info"><span class="codicon codicon-sync codicon-modifier-spin"></span> Installing</span>';
                    if (actionCell) {
                        actionCell.innerHTML = '';
                    }
                    break;
                case 'installed':
                    statusCell.innerHTML = '<span class="success">✓ Installed</span>';
                    if (actionCell) {
                        actionCell.innerHTML = '';
                    }
                    break;
                case 'pending-restart':
                    statusCell.innerHTML = '<span class="warning"><span class="codicon codicon-warning"></span> Not Available Pending Restart</span>';
                    if (actionCell) {
                        actionCell.innerHTML = '';
                    }
                    break;
                case 'error':
                    statusCell.innerHTML = '<span class="error">✗ Installation Failed</span>';
                    break;
            }
            break;
        }
    }
}

// Workspace Setup Progress Functions

/**
 * Handles workspace setup progress events by rendering a progress panel
 * at the top of the workspace setup sub-page. If the workspace sub-page
 * is not currently visible, the progress panel navigates to it first.
 * @param {object} data - The progress event data
 * @param {string} data.type - Event type: 'start', 'step-update', 'complete', or 'failed'
 * @param {string} data.operationLabel - Label for the operation
 * @param {Array} data.steps - Step objects: { id, label, status, detail? }
 * @param {string} [data.message] - Optional message
 */
function handleWorkspaceSetupProgress(data) {
    // A 'start' or 'step-update' event while not yet tracking means a setup
    // operation is in progress (e.g. panel opened mid-setup). Activate tracking.
    if (data.type === 'start' || data.type === 'step-update') {
        _workspaceSetupActive = true;
        updateWorkspaceCardStatus('initializing');
    }

    // On complete or failure, mark setup as no longer active.
    if (data.type === 'complete' || data.type === 'failed') {
        _workspaceSetupActive = false;
        updateWorkspaceCardStatus(data.type === 'complete' ? 'ready' : 'failed');
    }

    // Don't render progress panel unless relevant.
    if (!_workspaceSetupActive && data.type !== 'complete' && data.type !== 'failed') {
        return;
    }

    // Only update the workspace sub-page progress panel if it is already visible.
    // Never force-navigate — the user may be on the overview or another page.
    var subPageContainer = document.getElementById('subPageContainer');
    if (!subPageContainer || !subPageContainer.classList.contains('visible')) {
        // Workspace page not visible. State will be applied when the user
        // navigates to it (showSubPage checks _workspaceSetupActive).
        return;
    }

    // Ensure the initializing state is active.
    setWorkspaceState('initializing');

    // The progress container is pre-rendered inside .ws-state-initializing.
    var container = document.getElementById('setupProgressContainer');
    if (!container) {
        return;
    }

    // Clear any pending dismiss timer
    if (_setupProgressDismissTimer) {
        clearTimeout(_setupProgressDismissTimer);
        _setupProgressDismissTimer = null;
    }

    if (data.type === 'complete') {
        _setupProgressDismissTimer = setTimeout(function () {
            dismissSetupProgress();
        }, 8000);
    }

    // Determine header style based on event type
    let bannerClass, bannerIcon, bannerText;
    switch (data.type) {
        case 'complete':
            bannerClass = 'status-success';
            bannerIcon = '<span class="codicon codicon-check"></span>';
            bannerText = 'Setup Complete';
            break;
        case 'failed':
            bannerClass = 'status-error';
            bannerIcon = '<span class="codicon codicon-error"></span>';
            bannerText = 'Setup Failed';
            break;
        default:
            bannerClass = 'status-info';
            bannerIcon = '';
            bannerText = 'Setting Up Workspace...';
            break;
    }

    function getStepIcon(status) {
        switch (status) {
            case 'completed':
                return '<span class="setup-step-icon completed"><span class="codicon codicon-check"></span></span>';
            case 'in-progress':
                return '<span class="setup-step-icon in-progress"><span class="codicon codicon-sync codicon-modifier-spin"></span></span>';
            case 'failed':
                return '<span class="setup-step-icon failed"><span class="codicon codicon-error"></span></span>';
            case 'skipped':
                return '<span class="setup-step-icon skipped"><span class="codicon codicon-dash"></span></span>';
            default:
                return '<span class="setup-step-icon pending"><span class="codicon codicon-circle-outline"></span></span>';
        }
    }

    const stepsHtml = data.steps.map(function (step) {
        const detail = step.detail
            ? '<span class="setup-step-detail">' + escapeHtml(step.detail) + '</span>'
            : '';
        return '' +
            '<div class="setup-step-item ' + step.status + '">' +
            getStepIcon(step.status) +
            '<div class="setup-step-content">' +
            '<span class="setup-step-label">' + escapeHtml(step.label) + '</span>' +
            detail +
            '</div>' +
            '</div>';
    }).join('');

    const bannerSpinner = (data.type === 'start' || data.type === 'step-update')
        ? '<div class="loading-spinner"></div>'
        : '';

    const messageHtml = data.message
        ? '<p class="setup-progress-message">' + escapeHtml(data.message) + '</p>'
        : '';

    // Show a dismiss button when complete or failed
    const dismissBtn = (data.type === 'complete' || data.type === 'failed')
        ? '<button class="setup-progress-dismiss" onclick="dismissSetupProgress()" title="Dismiss">' +
        '<span class="codicon codicon-close"></span>' +
        '</button>'
        : '';

    const html = '' +
        '<div class="setup-progress-panel">' +
        '<div class="setup-progress-header ' + bannerClass + '">' +
        bannerSpinner +
        '<span class="status-icon">' + bannerIcon + '</span>' +
        '<span class="setup-progress-title">' + escapeHtml(data.operationLabel) + ' — ' + bannerText + '</span>' +
        dismissBtn +
        '</div>' +
        '<div class="setup-progress-body">' +
        '<div class="setup-progress-steps">' +
        stepsHtml +
        '</div>' +
        messageHtml +
        '</div>' +
        '</div>';

    container.innerHTML = html;
}

/** Dismiss / hide the progress panel content. */
function dismissSetupProgress() {
    var container = document.getElementById('setupProgressContainer');
    if (container) {
        // Clear content but keep the container in the DOM (it's part of the
        // pre-rendered initializing state and may be reused).
        container.innerHTML = '';
    }
    if (_setupProgressDismissTimer) {
        clearTimeout(_setupProgressDismissTimer);
        _setupProgressDismissTimer = null;
    }
}
