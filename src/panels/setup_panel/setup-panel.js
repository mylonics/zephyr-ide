/**
 * Set the workspace sub-page to one of its three mutually exclusive states:
 *   "initializing"    — a setup operation is running
 *   "ready"           — workspace is configured
 *   "setup-required"  — no workspace configured
 *
 * CSS rules on [data-workspace-state] hide/show the matching .ws-state-*
 * container, so no DOM surgery is needed — just flip the attribute.
 */
function setWorkspaceState(state) {
    var body = document.querySelector('.sub-page-body[data-workspace-state]');
    if (body) {
        body.setAttribute('data-workspace-state', state);
    }
}

/**
 * Update the workspace card on the overview page to reflect setup status.
 * @param {'initializing' | 'ready' | 'failed'} state
 */
function updateWorkspaceCardStatus(state) {
    var el = document.getElementById('workspaceCardStatus');
    if (!el) {
        return;
    }
    // Remove all status-* classes, then set the new one.
    el.className = 'status';
    switch (state) {
        case 'initializing':
            el.classList.add('status-info');
            el.innerHTML = '<div class="loading-spinner"></div> Initializing\u2026';
            break;
        case 'ready':
            el.classList.add('status-success');
            el.textContent = '\u2713 Initialized';
            break;
        case 'failed':
            el.classList.add('status-error');
            el.textContent = '\u2717 Setup Failed';
            break;
    }
}

/**
 * Switch to the initializing state.
 * Called immediately when any setup button is clicked so the user sees
 * instant feedback instead of the page appearing to hang.
 *
 * Only flips the state attribute if the workspace page is already rendered.
 * Does NOT force-navigate — the user is already on the workspace page when
 * clicking a setup button.
 */
function showWorkspaceInitializing() {
    // Mark setup as active so that if the user later navigates to the workspace
    // page, showSubPage will switch it to the initializing state.
    _workspaceSetupActive = true;

    var body = document.querySelector('.sub-page-body[data-workspace-state]');
    if (body) {
        // Container already rendered — just flip the state.
        body.setAttribute('data-workspace-state', 'initializing');
    }
    // If the workspace page isn't rendered, do nothing here.
    // showSubPage will check _workspaceSetupActive when the user navigates.

    // Update the overview card to reflect the initializing state.
    updateWorkspaceCardStatus('initializing');
}

